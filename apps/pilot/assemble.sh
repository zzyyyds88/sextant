#!/usr/bin/env bash
# Assemble a debug-signed APK from `apk/` sources (javac + d8 + aapt2 + apksigner).
# Usage: assemble.sh <apk-src-dir> <out.apk> <pkg>
set -euo pipefail

SRC=${1:?apk src dir}
OUT=${2:?output apk}
PKG=${3:?package name}
VERNAME=${4:-}
VERCODE=${5:-}
EXTRA_ASSETS=${6:-}
EXTRA_NATIVE=${7:-}

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
SDK=${ANDROID_SDK_ROOT:-"$ROOT/tools/android-sdk"}
BT=${ANDROID_BUILD_TOOLS:-"$SDK/build-tools/android-35"}
PLATFORM=${ANDROID_PLATFORM:-"$SDK/platforms/android-34/android.jar"}
AAPT2=${AAPT2:-"$BT/aapt2"}
D8=${D8:-"$BT/d8"}
ZIPALIGN=${ZIPALIGN:-"$BT/zipalign"}
APKSIGNER=${APKSIGNER:-"$BT/apksigner"}
KOTLINC=${KOTLINC:-"$ROOT/tools/kotlin/kotlinc/bin/kotlinc"}
KOTLIN_STDLIB=${KOTLIN_STDLIB:-"$ROOT/tools/kotlin/kotlinc/lib/kotlin-stdlib.jar"}

for t in "$AAPT2" "$D8" "$ZIPALIGN" "$APKSIGNER"; do
  [ -x "$t" ] || { echo "missing tool: $t" >&2; exit 1; }
done
[ -f "$PLATFORM" ] || { echo "missing platform: $PLATFORM" >&2; exit 1; }

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/gen" "$WORK/classes" "$WORK/kotlin-classes" "$WORK/dex" "$WORK/res" "$WORK/unsigned"

# ── resources ──
"$AAPT2" compile --dir "$SRC/res" -o "$WORK/res.zip"
LINK_ARGS=(-I "$PLATFORM" --manifest "$SRC/AndroidManifest.xml"
  --min-sdk-version 29 --target-sdk-version 33)
[ -n "$VERNAME" ] && LINK_ARGS+=(--version-name "$VERNAME")
[ -n "$VERCODE" ] && LINK_ARGS+=(--version-code "$VERCODE")
"$AAPT2" link "${LINK_ARGS[@]}" -o "$WORK/res/base.apk" --java "$WORK/gen" "$WORK/res.zip"

# ── sources ──
mapfile -t JAVASRCS < <(find "$SRC/src" -name '*.java' | sort)
mapfile -t KTSRCS  < <(find "$SRC/src" -name '*.kt'   | sort)
[ "${#JAVASRCS[@]}" -gt 0 ] || { echo "no java sources" >&2; exit 1; }

# R.java is generated by aapt2 link into $WORK/gen; compile it together with
# the Java sources so Kotlin can see R through the class dir.
mapfile -t GENS < <(find "$WORK/gen" -name 'R.java' | sort)
javac -encoding UTF-8 --release 8 -nowarn -classpath "$PLATFORM" -d "$WORK/classes" "${JAVASRCS[@]}" "${GENS[@]}"

if [ "${#KTSRCS[@]}" -gt 0 ]; then
  [ -x "$KOTLINC" ] || { echo "missing kotlinc: $KOTLINC" >&2; exit 1; }
  "$KOTLINC" -nowarn -cp "$PLATFORM:$WORK/classes" -d "$WORK/kotlin-classes" "${KTSRCS[@]}"
fi

# ── dex ──
D8_INPUTS=()
while IFS= read -r f; do D8_INPUTS+=("$f"); done < <(find "$WORK/classes" "$WORK/kotlin-classes" -name '*.class' 2>/dev/null | sort)
[ "${#D8_INPUTS[@]}" -gt 0 ] || { echo "no classes to dex" >&2; exit 1; }
KOTLIN_ARG=()
[ "${#KTSRCS[@]}" -gt 0 ] && KOTLIN_ARG=("$KOTLIN_STDLIB")
"$D8" --release --min-api 29 --lib "$PLATFORM" --output "$WORK/dex" "${D8_INPUTS[@]}" "${KOTLIN_ARG[@]}"

# ── assemble ──
cp "$WORK/res/base.apk" "$WORK/unsigned/app.apk"
( cd "$WORK/dex" && zip -q -j "$WORK/unsigned/app.apk" classes.dex )
if [ -n "$EXTRA_ASSETS" ] && [ -d "$EXTRA_ASSETS" ]; then
  rm -rf "$WORK/assets"; mkdir -p "$WORK/assets"
  cp -a "$EXTRA_ASSETS/." "$WORK/assets/"
  ( cd "$WORK" && zip -q -r "$WORK/unsigned/app.apk" assets )
fi
if [ -n "$EXTRA_NATIVE" ] && [ -d "$EXTRA_NATIVE" ]; then
  ( cd "$EXTRA_NATIVE" && zip -q -r "$WORK/unsigned/app.apk" . )
fi
# native libs must be stored uncompressed when extractNativeLibs=false;
# we use extractNativeLibs=true so compression is fine.

"$ZIPALIGN" -f 4 "$WORK/unsigned/app.apk" "$WORK/unsigned/aligned.apk"

# ── signing ──
#
# Development builds auto-create a local self-signed key under build/keystore.
# Release builds must name their key and password file explicitly, must not
# auto-generate anything, and pass the password through the environment rather
# than argv (argv is visible in `ps`). See docs/RELEASE.md.
DEFAULT_KEYDIR="$ROOT/apps/pilot/build/keystore"
KEYSTORE=${SEXTANT_KEYSTORE:-"$DEFAULT_KEYDIR/keystore.jks"}
PASSFILE=${SEXTANT_KEYSTORE_PASS_FILE:-"$DEFAULT_KEYDIR/keystore.pass"}
RELEASE=${SEXTANT_RELEASE:-0}
ALIAS=${SEXTANT_KEY_ALIAS:-}

if [ "$RELEASE" = "1" ]; then
  [ -n "${SEXTANT_KEYSTORE:-}" ] || { echo "release build needs SEXTANT_KEYSTORE" >&2; exit 1; }
  [ -n "${SEXTANT_KEYSTORE_PASS_FILE:-}" ] || { echo "release build needs SEXTANT_KEYSTORE_PASS_FILE" >&2; exit 1; }
  [ -f "$KEYSTORE" ] || { echo "release keystore not found: $KEYSTORE" >&2; exit 1; }
fi

if [ ! -f "$KEYSTORE" ]; then
  if [ "$KEYSTORE" != "$DEFAULT_KEYDIR/keystore.jks" ]; then
    echo "keystore not found: $KEYSTORE" >&2
    exit 1
  fi
  umask 077
  mkdir -p "$DEFAULT_KEYDIR"
  head -c 24 /dev/urandom | base64 | tr -d '\n' > "$PASSFILE"
  printf '\n' >> "$PASSFILE"
  PASS=$(head -n1 "$PASSFILE")
  keytool -genkeypair -keystore "$KEYSTORE" \
    -storepass "$PASS" -keypass "$PASS" -alias "$ALIAS" \
    -keyalg RSA -keysize 2048 -validity 36500 \
    -dname "CN=$PKG, OU=sextant, O=sextant, C=CN" 2>/dev/null
fi
[ -f "$PASSFILE" ] || { echo "keystore password file not found: $PASSFILE" >&2; exit 1; }
PASS=$(head -n1 "$PASSFILE")
# Existing project keystores predate the Sextant package rename and keep their
# original alias. Reuse the single PrivateKeyEntry unless the caller overrides it.
if [ -z "$ALIAS" ] && command -v keytool >/dev/null 2>&1; then
  ALIAS=$(keytool -list -keystore "$KEYSTORE" -storepass:file "$PASSFILE" 2>/dev/null \
    | awk -F, '/PrivateKeyEntry/{gsub(/^ +| +$/, "", $1); print $1; exit}')
fi
ALIAS=${ALIAS:-$PKG}
mkdir -p "$(dirname "$OUT")"
SEXTANT_KS_PASS="$PASS" "$APKSIGNER" sign --ks "$KEYSTORE" \
  --ks-pass env:SEXTANT_KS_PASS --key-pass env:SEXTANT_KS_PASS \
  --ks-key-alias "$ALIAS" --out "$OUT" "$WORK/unsigned/aligned.apk"
"$APKSIGNER" verify "$OUT" >/dev/null
echo "signed: $OUT"
